// Package gen generates validators for validate Object schemas.
//
// What is generated is only the object structure: the field loop, assignment
// into the struct, unknown-key handling and object refinements, with no
// reflection. Every leaf (strings, numbers, arrays, enums, transforms,
// unions, ...) still runs on the schema's own runtime engine, fetched with
// validate.LeafAt. There is therefore no second implementation of any rule to
// drift out of sync; the generated code and the runtime differ only in how
// objects are walked.
//
// Typical use is a small program next to your schemas:
//
//	//go:build ignore
//	package main
//
//	func main() {
//	    src, err := gen.Generate(gen.Config{Package: "api", Targets: []gen.Target{
//	        {Name: "CreateUserFast", Expr: "CreateUserSchema", Schema: api.CreateUserSchema},
//	    }})
//	    ...
//	    os.WriteFile("validators_gen.go", src, 0o644)
//	}
//
// and then use api.CreateUserFast anywhere a Schema is accepted. If the schema
// structure changes and the file is not regenerated, the fingerprint no longer
// matches and validate.Generated falls back to the runtime schema.
package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"reflect"
	"regexp"
	"sort"
	"strings"
	"unicode"

	validate "github.com/tobibamidele/validate"
)

// Target is one schema to generate a validator for.
type Target struct {
	// Name is the exported variable the generated validator is assigned to.
	Name string
	// Expr is the Go expression naming the runtime schema in the generated
	// package, e.g. "CreateUserSchema".
	Expr string
	// Schema is the same schema as a value, used to read its structure.
	Schema any
}

// Config configures Generate.
type Config struct {
	// Package is the package clause of the generated file. It must be the
	// package that declares the schemas' target types.
	Package string
	Targets []Target
}

// Generate returns the formatted Go source for cfg.
func Generate(cfg Config) ([]byte, error) {
	if cfg.Package == "" {
		return nil, fmt.Errorf("gen: empty package name")
	}
	if len(cfg.Targets) == 0 {
		return nil, fmt.Errorf("gen: no targets")
	}
	e := &emitter{imports: map[string]string{}, used: map[string]bool{"validate": true}}
	var body bytes.Buffer
	e.out = &body
	seen := map[string]bool{}
	for i, t := range cfg.Targets {
		if t.Name == "" || t.Expr == "" {
			return nil, fmt.Errorf("gen: target %d needs Name and Expr", i)
		}
		if seen[t.Name] {
			return nil, fmt.Errorf("gen: duplicate target name %q", t.Name)
		}
		seen[t.Name] = true
		info, ok := validate.InspectObject(t.Schema)
		if !ok {
			return nil, fmt.Errorf("gen: target %s: only Object schemas can be generated (got %T)", t.Name, t.Schema)
		}
		if e.pkgPath == "" {
			e.pkgPath = info.GoType.PkgPath()
		} else if e.pkgPath != info.GoType.PkgPath() {
			return nil, fmt.Errorf("gen: target %s: all targets must live in one package (%s vs %s)", t.Name, e.pkgPath, info.GoType.PkgPath())
		}
		fp, _ := validate.Fingerprint(t.Schema)
		e.target(t, info, fp)
		if e.err != nil {
			return nil, fmt.Errorf("gen: target %s: %w", t.Name, e.err)
		}
	}
	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by validate/gen. DO NOT EDIT.\n\npackage %s\n\nimport (\n", cfg.Package)
	fmt.Fprintf(&src, "\tvalidate %q\n", "github.com/tobibamidele/validate")
	paths := make([]string, 0, len(e.imports))
	for p := range e.imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		fmt.Fprintf(&src, "\t%s %q\n", e.imports[p], p)
	}
	src.WriteString(")\n\n")
	src.Write(body.Bytes())
	out, err := format.Source(src.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gen: generated code does not parse (bug): %w\n%s", err, src.String())
	}
	return out, nil
}

type emitter struct {
	out     *bytes.Buffer
	pkgPath string
	imports map[string]string // path -> alias
	used    map[string]bool   // aliases in use
	n       int               // unique name counter
	err     error
	leaves  []leafDecl
}

type leafDecl struct{ name, typ, expr string }

func (e *emitter) fail(format string, args ...any) {
	if e.err == nil {
		e.err = fmt.Errorf(format, args...)
	}
}

func (e *emitter) fresh(prefix string) string {
	e.n++
	return fmt.Sprintf("%s%d", prefix, e.n)
}

func (e *emitter) w(format string, args ...any) { fmt.Fprintf(e.out, format, args...) }

// ---- type rendering ----

var qualified = regexp.MustCompile(`([A-Za-z0-9_./~-]+)\.([A-Za-z_][A-Za-z0-9_]*)`)

func (e *emitter) qual(path string) string {
	if path == e.pkgPath {
		return ""
	}
	if path == "github.com/tobibamidele/validate" {
		return "validate."
	}
	if a, ok := e.imports[path]; ok {
		return a + "."
	}
	base := path[strings.LastIndex(path, "/")+1:]
	alias := strings.Map(func(r rune) rune {
		if unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_' {
			return r
		}
		return '_'
	}, base)
	for i := 2; e.used[alias]; i++ {
		alias = fmt.Sprintf("%s%d", base, i)
	}
	e.used[alias] = true
	e.imports[path] = alias
	return alias + "."
}

func (e *emitter) typ(t reflect.Type) string {
	if t.Name() != "" && t.PkgPath() != "" {
		name := t.Name()
		base, args := name, ""
		if i := strings.IndexByte(name, '['); i >= 0 {
			base, args = name[:i], name[i:]
		}
		if t.PkgPath() != e.pkgPath && !ast_isExported(base) {
			e.fail("type %s is unexported in another package", t)
		}
		args = qualified.ReplaceAllStringFunc(args, func(m string) string {
			sub := qualified.FindStringSubmatch(m)
			return e.qual(sub[1]) + sub[2]
		})
		return e.qual(t.PkgPath()) + base + args
	}
	switch t.Kind() {
	case reflect.Ptr:
		return "*" + e.typ(t.Elem())
	case reflect.Slice:
		return "[]" + e.typ(t.Elem())
	case reflect.Array:
		return fmt.Sprintf("[%d]%s", t.Len(), e.typ(t.Elem()))
	case reflect.Map:
		return "map[" + e.typ(t.Key()) + "]" + e.typ(t.Elem())
	case reflect.Interface:
		if t.NumMethod() == 0 {
			return "any"
		}
	}
	return t.String()
}

func ast_isExported(name string) bool {
	for _, r := range name {
		return unicode.IsUpper(r)
	}
	return false
}

// ---- emission ----

func (e *emitter) target(t Target, info validate.ObjectInfo, fp string) {
	e.leaves = nil
	var body bytes.Buffer
	saved := e.out
	e.out = &body
	e.body(info, nil, t.Expr)
	e.out = saved

	rt := e.typ(info.GoType)
	e.w("var %s = validate.Generated[%s](%s, %q, func() validate.GenFunc[%s] {\n", t.Name, rt, t.Expr, fp, rt)
	for _, l := range e.leaves {
		e.w("\t%s\n", l.expr)
	}
	e.w("\treturn func(c validate.Scope, in validate.Input) (%s, bool) {\n", rt)
	e.w("%s", body.String())
	e.w("\t}\n})\n\n")
}

func quoteList(names []string) string {
	q := make([]string, len(names))
	for i, n := range names {
		q[i] = fmt.Sprintf("%q", n)
	}
	return strings.Join(q, ", ")
}

// body emits the statements of one object validator. It reads `c` and `in`
// and returns (T, bool), so it serves both the root function and nested
// function literals.
func (e *emitter) body(info validate.ObjectInfo, path []string, root string) {
	rt := e.typ(info.GoType)
	e.w("var zero %s\n", rt)
	e.w("m, ok := c.Map(in)\nif !ok {\n\treturn zero, false\n}\n")
	e.w("mark := c.Mark()\nvar out %s\n", rt)

	known := make([]string, 0, len(info.Fields))
	for _, f := range info.Fields {
		known = append(known, f.Name)
		fpath := append(append([]string(nil), path...), f.Name)
		if f.ViaPointer {
			e.fail("field %q is promoted through an embedded pointer, which generated code cannot assign", f.Name)
			return
		}
		e.w("{\n\tfc := c.Child(%q)\n\traw, present := m[%q]\n\tfin := validate.Input{V: raw, Present: present}\n", f.Name, f.Name)
		if f.Nested != nil {
			nrt := e.typ(f.Nested.GoType)
			e.w("\tv, ok := func(c validate.Scope, in validate.Input) (%s, bool) {\n", nrt)
			e.body(*f.Nested, fpath, root)
			e.w("\t}(fc, fin)\n")
		} else {
			leaf := e.fresh("leaf")
			vt := e.typ(f.OutType)
			e.leaves = append(e.leaves, leafDecl{leaf, vt,
				fmt.Sprintf("%s := validate.LeafAt[%s](%s, %s)", leaf, vt, root, quoteList(fpath))})
			e.w("\tv, ok := %s(fc, fin)\n", leaf)
		}
		e.w("\tif ok {\n")
		e.assign("out."+strings.Join(f.GoPath, "."), "v", f.OutType, f.GoType)
		e.w("\t}\n\tif c.Stop() {\n\t\treturn zero, false\n\t}\n}\n")
	}
	if info.Strict {
		e.w("c.Unknown(m, []string{%s})\n", quoteList(known))
	}
	e.w("if c.Failed(mark) {\n\treturn zero, false\n}\n")
	if info.Refines > 0 {
		r := e.fresh("refines")
		e.leaves = append(e.leaves, leafDecl{r, "", fmt.Sprintf("%s := validate.RefinesAt[%s](%s%s)", r, rt, root, joinArgs(path))})
		e.w("if !validate.RunRefine(c, in, out, %s) {\n\treturn zero, false\n}\n", r)
	}
	e.w("return out, true\n")
}

func joinArgs(path []string) string {
	if len(path) == 0 {
		return ""
	}
	return ", " + quoteList(path)
}

// assign mirrors the runtime's planAssign decision order exactly: direct,
// then unwrap Optional/Nullable, then pointer.
func (e *emitter) assign(dst, src string, st, dt reflect.Type) {
	switch {
	case st.AssignableTo(dt):
		e.w("%s = %s\n", dst, src)
	default:
		if inner, ok := validate.WrappedType(st); ok {
			x := e.fresh("x")
			set := e.fresh("set")
			e.w("if %s, %s := %s.Value(); %s {\n", x, set, src, set)
			e.assign(dst, x, inner, dt)
			e.w("}\n")
			return
		}
		if dt.Kind() == reflect.Ptr {
			p := e.fresh("p")
			e.w("%s := new(%s)\n", p, e.typ(dt.Elem()))
			e.assign("*"+p, src, st, dt.Elem())
			e.w("%s = %s\n", dst, p)
			return
		}
		e.fail("cannot assign %s to %s", st, dt)
	}
}
