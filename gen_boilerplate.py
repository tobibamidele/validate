out = ['// Code generated by gen_boilerplate.py; DO NOT EDIT.\n','package validate\n','import (\n\t"time"\n\n\t"github.com/google/uuid"\n)\n']
for name, tp, t in types:
    if tp:
        names = ", ".join(p.split()[0].rstrip(",") for p in tp.replace(",", " ,").split(",") if p.strip()) if False else None
    # receiver type parameter list names only
    if name == "TransformSchema": recv = "TransformSchema[A, B]"
    elif tp: recv = f"{name}[T]"
    else: recv = name
